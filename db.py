_INSERT_RE = re.compile(r'^\s*INSERT\s+INTO\s+([\w".]+)', re.IGNORECASE)
_DDL_RE = re.compile(r'^\s*(CREATE|ALTER|DROP)\b', re.IGNORECASE)

# DDL that cannot change the set of tables or their columns, so it must not
# invalidate the cached catalog lookups.
_INDEX_OR_SCHEMA_RE = re.compile(
    r'^\s*(?:CREATE|DROP)\s+(?:OR\s+REPLACE\s+)?'
    r'(?:UNIQUE\s+)?(?:INDEX|SCHEMA|SEQUENCE|EXTENSION)\b',
    re.IGNORECASE,
)

# Statements that are safe to replay after a reconnect.
_READ_ONLY_RE = re.compile(r'^\s*(SELECT|WITH|SHOW|EXPLAIN)\b', re.IGNORECASE)

# DDL that is safe to replay: the statement declares its own no-op behaviour,
# so running it twice leaves the schema exactly as running it once would. The
# guarded forms are the point - a bare "CREATE TABLE t" must never be retried,
# because the first attempt may well have succeeded before the socket died.
_IDEMPOTENT_DDL_RE = re.compile(
    r'^\s*(?:'
    r'CREATE\s+(?:OR\s+REPLACE\s+)?'
    r'(?:TABLE|INDEX|VIEW|MATERIALIZED\s+VIEW|SEQUENCE|SCHEMA|FUNCTION|TRIGGER)'
    r'(?:\s+IF\s+NOT\s+EXISTS)?\b'
    r'|DROP\s+(?:TABLE|INDEX|VIEW|MATERIALIZED\s+VIEW|SEQUENCE|SCHEMA|FUNCTION|TRIGGER)'
    r'(?:\s+IF\s+EXISTS|\s+CASCADE|\s+RESTRICT)?\b'
    r'|ALTER\s+TABLE\s+[\w".]+\s+ADD\s+COLUMN\s+IF\s+NOT\s+EXISTS\b'
    r')',
    re.IGNORECASE,
)

# SQLSTATEs meaning the server or the transport went away.
_CONN_LOST_SQLSTATES = frozenset({
    '08000',  # connection_exception
    '08001',  # sqlclient_unable_to_establish_sqlconnection
    '08003',  # connection_does_not_exist
    '08004',  # sqlserver_rejected_establishment_of_sqlconnection
    '08006',  # connection_failure
    '08007',  # transaction_resolution_unknown
    '08P01',  # protocol_violation
    '53300',  # too_many_connections
    '57P01',  # admin_shutdown
    '57P02',  # crash_shutdown
    '57P03',  # cannot_connect_now
})


def _is_connection_lost(exc):
    """True when ``exc`` means the connection to the server went away.

    ``Connection.execute`` re-raises psycopg errors through :func:`_translate_error`
    as HealthBridge ``DatabaseError`` subclasses, which carry no SQLSTATE of their
    own - so both the wrapper and its ``__cause__`` are inspected. psycopg also
    surfaces some of these only in the message text ("the connection is lost",
    "server closed the connection unexpectedly"), hence the substring check.
    """
    needles = (
        'connection is lost',
        'connection already closed',
        'server closed the connection',
        'terminating connection',
        'consuming input failed',
        'connection timeout expired',
        'ssl connection has been closed',
    )
    for err in (exc, getattr(exc, '__cause__', None)):
        if err is None:
            continue
        if getattr(err, 'sqlstate', None) in _CONN_LOST_SQLSTATES:
            return True
        msg = str(err).lower()
        if any(needle in msg for needle in needles):
            return True
    return False


class Cursor:
    """Wraps a psycopg cursor, adding ``lastrowid`` and sqlite-ish row factories.

    ``cur`` may be ``None`` for a statement that was answered from the schema
    cache instead of being sent to the server; the fetch methods then behave like
    an exhausted cursor, which is what such a no-op statement would return.
    """

    def __init__(self, connection, cur, raw_sql):
        self._conn = connection
        self._cur = cur
        self._raw_sql = raw_sql
        self.lastrowid = None
        self.rowcount = -1
        self.description = None
        self.arraysize = 1

    # -- iteration / fetching ------------------------------------------------
    def fetchone(self):
        if self._cur is None:
            return None
        row = self._cur.fetchone()
        return self._coerce(row)

    def fetchmany(self, size=None):
        if self._cur is None:
            return []
        rows = self._cur.fetchmany(size) if size is not None else self._cur.fetchmany()
        return [self._coerce(r) for r in rows]

    def fetchall(self):
        if self._cur is None:
            return []
        rows = self._cur.fetchall()
        return [self._coerce(r) for r in rows]

    def __iter__(self):
        if self._cur is None:
            return iter(())
        for row in self._cur:
            yield self._coerce(row)

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False

    def close(self):
        try:
            self._cur.close()
        except Exception:
            pass

    # -- passthrough ---------------------------------------------------------
    def __getattr__(self, name):
        return getattr(self._cur, name)

    def _coerce(self, row):
        """psycopg returns tuples; wrap them in Row when row_factory is set."""
        if self._conn.row_factory is Row and row is not None:
            names = [d.name for d in (self._cur.description or [])]
            return Row({n: _normalise(v) for n, v in zip(names, row)})
        if self._conn.row_factory is None and row is not None:
            return tuple(_normalise(v) for v in row)
        return row


class RawCursor:
    """DBAPI cursor wrapper that runs statements through the SQL translator.

    :meth:`Connection.execute` returns a :class:`Cursor`, but callers such as
    ``pandas.read_sql_query`` obtain a cursor directly and drive ``execute``
    themselves. Those statements have to be translated too, or bare table names
    are resolved via ``search_path``.
    """

    def __init__(self, connection, cur):
        self._conn = connection
        self._cur = cur

    def execute(self, sql, parameters=None, **kwargs):
        translated = translate_sql(
            sql,
            self._conn._boolean_columns(),
            schema=self._conn.schema,
            tables=self._conn._tables(),
        )
        with self._conn._lock:
            self._cur.execute(translated, list(parameters) if parameters else None)
        return self

    def executemany(self, sql, seq_of_params):
        for params in seq_of_params:
            self.execute(sql, params)
        return self

    # -- introspection used by pandas ---------------------------------------
    @property
    def description(self):
        return self._cur.description

    @property
    def rowcount(self):
        return self._cur.rowcount

    @property
    def rownumber(self):
        return self._cur.rownumber

    @property
    def connection(self):
        return self._conn

    def fetchone(self):
        return self._cur.fetchone()

    def fetchmany(self, size=None):
        return self._cur.fetchmany(size) if size is not None else self._cur.fetchmany()

    def fetchall(self):
        return self._cur.fetchall()

    def nextset(self):
        return self._cur.nextset()

    def setinputsizes(self, sizes):
        return self._cur.setinputsizes(sizes)

    def setoutputsize(self, size, column=None):
        return self._cur.setoutputsize(size, column)

    def close(self):
        try:
            self._cur.close()
        except Exception:
            pass

    def __iter__(self):
        return iter(self._cur)

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False

    def __getattr__(self, name):
        return getattr(self._cur, name)


class Connection:
    """DBAPI-ish connection bound to one PostgreSQL schema."""

    def __init__(self, dsn, schema):
        self.schema = schema
        self.row_factory = None
        self._shared = False
        self._id_columns = {}
        self._bool_cols = None
        self._all_cols = None
        self._index_names = None
        self._table_names = None
        self._lock = threading.RLock()
        self._dsn = dsn
        self._ensure_schema(dsn, schema)
        self._pg = _get_psycopg().connect(dsn, **_connect_kwargs())
        # Kept as a convenience for ad-hoc queries, but the SQL translator
        # schema-qualifies every table reference, because PgBouncer transaction
        # pooling does not reliably preserve this setting between transactions.
        _init_session(self._pg, schema)

    def _note_ddl(self, sql):
        """Keep the cached catalog lookups in step with a DDL statement.

        The guarded forms this codebase actually issues -
        ``CREATE TABLE IF NOT EXISTS`` and ``ADD COLUMN IF NOT EXISTS`` - have a
        predictable effect on the cached metadata, so the caches can be updated
        in place instead of dropped. Anything else (a bare CREATE/DROP, an
        unexpected form) falls back to a full invalidation, which is always
        correct, merely slower.

        Note this is best-effort bookkeeping: if a statement fails, the caller
        re-raises and the process usually stops anyway, and the worst case for a
        wrong guess is one stale entry that a later ``CREATE TABLE`` would
        surface as "already exists".
        """
        statement = sql.strip()

        # CREATE INDEX / DROP INDEX / CREATE SCHEMA never change the set of
        # tables or their columns, so those caches are still accurate - but the
        # index set itself does change, so refresh just that one.
        if _INDEX_OR_SCHEMA_RE.match(statement):
            if re.match(r'^\s*(?:CREATE|DROP)\s+(?:OR\s+REPLACE\s+)?(?:UNIQUE\s+)?INDEX\b',
                        statement, re.IGNORECASE):
                self._index_names = None
            return

        match = _CREATE_TABLE_NAME_RE.match(statement) or _CREATE_TABLE_NAME_UNQUALIFIED_RE.match(statement)
        if match:
            name = (match.group('name') or match.group('bare') or '').lower()
            if name:
                if self._table_names is not None:
                    self._table_names.add(name)
                # A brand-new table has no columns yet, and the CREATE body in
                # this codebase is not parsed here, so drop just that entry.
                if self._all_cols is not None:
                    self._all_cols.pop(name, None)
                self._id_columns.pop(name, None)
            return

        match = _ADD_COLUMN_NAME_RE.match(statement)
        if match:
            name = (match.group('name') or match.group('bare') or '')
            declared = (match.group('type') or '').strip().upper()
            table = _alter_target_table(statement)
            # Only the BOOLEAN set is cached, so a column of any other type
            # cannot make _bool_cols stale. ADD COLUMN never changes whether a
            # table has an "id" column, so _id_columns stays valid too.
            if name and declared.startswith('BOOL') and self._bool_cols is not None:
                self._bool_cols.add(name)
            if name and table and self._all_cols is not None:
                self._all_cols.setdefault(table, set()).add(name.lower())
            return

        # DROP TABLE, or anything we cannot model: be conservative.
        self._bool_cols = None
        self._all_cols = None
        self._index_names = None
        self._table_names = None
        self._id_columns.clear()

    def _reconnect(self):
        """Replace the underlying connection after the server dropped it.

        Neon's ``-pooler`` endpoint recycles server-side connections, so a
        long-lived pooled connection can die between statements. psycopg does not
        necessarily mark that as closed - ``transaction_status`` still reports
        IDLE because nothing touched the wire - so the health check in
        :func:`_acquire` cannot see it and the next statement fails with
        "the connection is lost". Rebuilding the socket here, and retrying the
        statement once, turns a hard error into a transparent reconnect.
        """
        try:
            self._pg.close()
        except Exception:
            pass
        self._pg = _get_psycopg().connect(self._dsn, **_connect_kwargs())
        _init_session(self._pg, self.schema)
        # Column/table metadata may differ on the new backend session.
        self._bool_cols = None
        self._all_cols = None
        self._index_names = None
        self._table_names = None
        self._id_columns.clear()

    # -- lifecycle ----------------------------------------------------------
    def commit(self):
        with self._lock:
            self._pg.commit()

    def rollback(self):
        with self._lock:
            self._pg.rollback()

    def close(self):
        """Close the connection, unless it is a shared one from the cache."""
        if getattr(self, '_shared', False):
            _release(self.schema, self)
            return
        try:
            self._pg.close()
        except Exception:
            pass

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False

    # -- execution ----------------------------------------------------------
    def execute(self, sql, parameters=None):
        """Run one statement, transparently reconnecting if the server dropped us."""
        try:
            return self._execute_once(sql, parameters)
        except Exception as exc:
            # Replay only what is safe to run twice. A read-only statement cannot
            # change anything, and the guarded DDL forms are no-ops when the
            # object already exists. A plain INSERT/UPDATE/DELETE, or DDL
            # without an IF [NOT] EXISTS guard, is surfaced instead: if such a
            # statement lost its connection there is no way to know whether the
            # server applied it first, so retrying could duplicate the row.
            statement = sql.strip()
            replayable = _READ_ONLY_RE.match(statement) or _IDEMPOTENT_DDL_RE.match(statement)
            if not (_is_connection_lost(exc) and replayable):
                raise
            try:
                self._reconnect()
            except Exception:
                raise exc
            return self._execute_once(sql, parameters)

    def _execute_once(self, sql, parameters=None):
        translated = translate_sql(
            sql,
            self._boolean_columns(),
            schema=self.schema,
            tables=self._tables(),
        )
        params = list(parameters) if parameters else None

        translated, params, want_id = self._prepare_insert(translated, params)

        is_ddl = bool(_DDL_RE.match(translated))

        # A guarded CREATE/ALTER/INDEX that the catalog shows is already satisfied
        # is a guaranteed no-op. Answering it from the cache instead of sending it
        # keeps the ~45 such statements the app issues at import off the wire,
        # where each costs about a second through Neon's pooler - that alone was
        # over a hundred seconds of startup. The check runs on the *translated*
        # statement, because that is where the translator has added the
        # ``IF NOT EXISTS`` guard and schema-qualified the names.
        # ``_all_statements_noop`` returns False unless every part is certain, so
        # this can only ever skip work that would have changed nothing.
        if is_ddl and not params:
            try:
                if self._all_statements_noop(translated):
                    return Cursor(self, None, sql)
            except Exception:
                # Never let the optimisation itself break a statement; fall
                # through and let the server be the judge.
                pass

        # DDL can introduce or drop tables/columns, so the cached catalog
        # lookups can go stale. Blanket-invalidating them here is correct but
        # ruinously slow: every init_db() issues dozens of CREATE TABLE IF NOT
        # EXISTS / ADD COLUMN IF NOT EXISTS statements, and each invalidation
        # forces the *next* statement to re-query information_schema. Behind
        # Neon's pooler a round trip costs about a second, so the app spent well
        # over a hundred seconds at import re-reading a catalog that had not
        # actually changed. Update the caches from the statement text instead,
        # and only fall back to a full invalidation for DDL we cannot model.
        if is_ddl:
            self._note_ddl(translated)

        # Set when a failed DDL statement has already been rolled back to its
        # savepoint, which leaves the transaction usable - see below.
        savepoint_restored = False

        try:
            # Shared connections are used from Flask's threaded dev server, and
            # a psycopg connection cannot interleave two operations.
            with self._lock:
                cur = self._pg.cursor()
                if is_ddl:
                    # init_db()/init_database() run a CREATE TABLE immediately
                    # followed by an "ADD COLUMN if it doesn't exist" probe that
                    # is *expected* to fail. In SQLite a failed statement leaves
                    # earlier work in the transaction intact, but in PostgreSQL
                    # any error aborts the whole transaction and would undo the
                    # CREATE TABLE. A savepoint confines the damage to the one
                    # statement that failed.
                    cur.execute('SAVEPOINT hb_stmt')
                try:
                    cur.execute(translated, params)
                except Exception:
                    if is_ddl:
                        try:
                            cur.execute('ROLLBACK TO SAVEPOINT hb_stmt')
                            # The savepoint already put the transaction back in a
                            # usable state. Rolling the whole thing back here
                            # would undo the CREATE TABLEs that ran earlier in
                            # this same transaction - which is exactly what the
                            # savepoint exists to prevent.
                            savepoint_restored = True
                        except Exception:
                            pass
                    raise
                if is_ddl:
                    cur.execute('RELEASE SAVEPOINT hb_stmt')
        except Exception as exc:
            if not savepoint_restored:
                try:
                    self._pg.rollback()
                except Exception:
                    pass
            raise _translate_error(exc) from exc

        cursor = Cursor(self, cur, sql)
        cursor.description = cur.description
        try:
            cursor.rowcount = cur.rowcount
        except Exception:
            pass

        if want_id:
            try:
                row = cur.fetchone()
                if row:
                    cursor.lastrowid = row[0]
                    cursor._insert_id_row = row
            except Exception:
                cursor.lastrowid = None

        return cursor

    def executemany(self, sql, seq_of_params):
        cur = self.execute(sql, ())
        for params in seq_of_params:
            self.execute(sql, params)
        return cur

    def executescript(self, script):
        for stmt in _split_statements(script):
            self.execute(stmt)

    def cursor(self, *args, **kwargs):
        """A DBAPI cursor that still schema-qualifies statements.

        Used by ``pandas.read_sql_query``, which grabs a cursor and calls
        ``execute()`` itself - so it would otherwise bypass the translator and
        resolve bare table names through ``search_path``, which the -pooler host
        (PgBouncer, transaction pooling) does not preserve between transactions.
        """
        return RawCursor(self, self._pg.cursor(*args, **kwargs))

    def commit_on_close(self):
        pass

    # -- internals ----------------------------------------------------------
    def _columns(self):
        """{table: {column}} for this schema (cached, refreshed by DDL).

        One catalog query replaces the per-statement ``information_schema``
        lookups that deciding whether a guarded ``ADD COLUMN`` is a no-op would
        otherwise need. That matters because the app issues dozens of them at
        import and each round trip through Neon's pooler costs about a second.
        """
        if self._all_cols is not None:
            return self._all_cols
        cur = self._pg.cursor()
        try:
            cur.execute(
                """
                SELECT table_name, column_name
                FROM information_schema.columns
                WHERE table_schema = %s
                """,
                (self.schema,),
            )
            cols = {}
            for table, column in cur.fetchall():
                cols.setdefault(table.lower(), set()).add(column.lower())
            self._all_cols = cols
        except Exception:
            self._pg.rollback()
            self._all_cols = {}
        finally:
            cur.close()
        return self._all_cols

    def _indexes(self):
        """Lower-cased index names in this schema (cached, refreshed by DDL)."""
        if self._index_names is not None:
            return self._index_names
        cur = self._pg.cursor()
        try:
            cur.execute(
                """
                SELECT indexname
                FROM pg_indexes
                WHERE schemaname = %s
                """,
                (self.schema,),
            )
            self._index_names = {r[0].lower() for r in cur.fetchall()}
        except Exception:
            self._pg.rollback()
            self._index_names = set()
        finally:
            cur.close()
        return self._index_names

    def _is_noop_ddl(self, sql):
        """True when a guarded DDL statement provably changes nothing.

        ``CREATE TABLE IF NOT EXISTS`` for a table the catalog already lists,
        ``ADD COLUMN IF NOT EXISTS`` for a column the table already has, and
        ``CREATE INDEX IF NOT EXISTS`` for an index that exists are guaranteed
        no-ops in PostgreSQL. Answering those from the cache instead of sending
        them is semantically identical, and it is the difference between a
        network round trip each and nothing at all.

        Returns False whenever there is any doubt, so an unrecognised or
        unguarded statement always reaches the server.
        """
        statement = sql.strip()
        if not statement:
            return False

        match = _CREATE_INDEX_NAME_RE.match(statement)
        if match:
            if not _IF_NOT_EXISTS_RE.search(statement):
                return False
            name = (match.group('name') or match.group('bare') or '').lower()
            return bool(name) and self._index_names is not None and name in self._index_names

        match = _CREATE_TABLE_NAME_RE.match(statement) or _CREATE_TABLE_NAME_UNQUALIFIED_RE.match(statement)
        if match:
            if not _IF_NOT_EXISTS_RE.search(statement):
                return False
            name = (match.group('name') or match.group('bare') or '').lower()
            return bool(name) and self._table_names is not None and name in self._table_names

        match = _ADD_COLUMN_NAME_RE.match(statement)
        if match:
            if not _IF_NOT_EXISTS_RE.search(statement):
                return False
            column = (match.group('name') or match.group('bare') or '').lower()
            table = _alter_target_table(statement)
            if not column or not table:
                return False
            existing = self._columns().get(table)
            return existing is not None and column in existing

        return False

    def _all_statements_noop(self, sql):
        """True when every statement in ``sql`` is a provable no-op.

        The translator turns ``ALTER TABLE ... ADD COLUMN c TEXT UNIQUE`` into two
        statements (the ALTER plus a companion unique index). Skipping the pair
        is only safe when *both* halves are already satisfied, so each statement
        is checked on its own.
        """
        parts = [p for p in _split_statements(sql) if p.strip()]
        if not parts:
            return False
        return all(self._is_noop_ddl(part) for part in parts)

    def _tables(self):
        """Lower-cased table names in this schema (cached, cleared by DDL)."""
        if self._table_names is not None:
            return self._table_names
        cur = self._pg.cursor()
        try:
            cur.execute(
                """
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = %s
                """,
                (self.schema,),
            )
            self._table_names = {r[0].lower() for r in cur.fetchall()}
        except Exception:
            self._pg.rollback()
            self._table_names = set()
        finally:
            cur.close()
        return self._table_names

    def _boolean_columns(self):
        """Names of BOOLEAN columns in this schema (cached, refreshed on DDL)."""
        if self._bool_cols is not None:
            return self._bool_cols
        cur = self._pg.cursor()
        try:
            cur.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = %s AND data_type = 'boolean'
                """,
                (self.schema,),
            )
            self._bool_cols = {r[0] for r in cur.fetchall()}
        except Exception:
            self._pg.rollback()
            self._bool_cols = set()
        finally:
            cur.close()
        return self._bool_cols

    def _prepare_insert(self, sql, params):
        """Append RETURNING id to INSERTs so ``cursor.lastrowid`` works."""
        m = _INSERT_RE.match(sql)
        if not m:
            return sql, params, False
        if 'RETURNING' in sql.upper():
            return sql, params, False
        table = _unqualify(m.group(1))
        if not self._has_id_column(table):
            return sql, params, False
        stripped = sql.rstrip()
        if stripped.endswith(';'):
            stripped = stripped[:-1]
        return stripped + ' RETURNING id', params, True

    def _has_id_column(self, table):
        """Cached check for whether a table has a plain ``id`` column."""
        if table in self._id_columns:
            return self._id_columns[table]
        cur = self._pg.cursor()
        try:
            cur.execute(
                """
                SELECT a.attname
                FROM pg_attribute a
                JOIN pg_class c ON c.oid = a.attrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = %s AND c.relname = %s
                  AND a.attname = 'id' AND a.attnum > 0 AND NOT a.attisdropped
                """,
                (self.schema, table.lower()),
            )
            found = cur.fetchone() is not None
        except Exception:
            # This lookup is only an optimisation; never let it break an INSERT.
            self._pg.rollback()
            found = False
        finally:
            cur.close()
        self._id_columns[table] = found
        return found

    @staticmethod
    def _ensure_schema(dsn, schema):
        """Create every schema the app maps to, over a single connection.

        Connecting to Neon is expensive: the ``-pooler`` endpoint adds a few
        seconds per handshake, and a free-tier compute that has just woken from
        suspension adds more. Opening a throwaway connection per schema doubled
        the connection count - and so the startup time - for no benefit, because
        ``CREATE SCHEMA IF NOT EXISTS`` is idempotent and can create them all in
        one pass the first time anything connects. After that first call this is
        just an in-memory set lookup.

        The statements are sent as one batched execute for the same reason: a
        round trip through the pooler costs about a second, and five separate
        CREATE SCHEMA statements cost five of them.
        """
        if schema in _created_schemas:
            return

        missing = sorted({schema, *SCHEMA_MAP.values()} - _created_schemas)
        statements = '; '.join(
            f'CREATE SCHEMA IF NOT EXISTS "{name}"' for name in missing
        )
        with _get_psycopg().connect(dsn, **{**_connect_kwargs(), 'autocommit': True}) as pg:
            with pg.cursor() as cur:
                cur.execute(statements)
        _created_schemas.update(missing)


# --------------------------------------------------------------------------- #
# Connection pool
# --------------------------------------------------------------------------- #
# The app opens a connection for nearly every operation (62 call sites across the
# nine data modules). Opening a real socket each time would exhaust Neon's
# connection limit, so each schema keeps one live connection that is handed out
# repeatedly and returned by close().

_pool = {}


def _acquire(dsn, schema):
    """Return the shared connection for ``schema``, creating it if needed."""
    conn = _pool.get(schema)
    if conn is not None and not conn._pg.closed:
        try:
            # Never hand out a connection that is mid-aborted-transaction.
            if conn._pg.info.transaction_status != _get_pg_status_idle():
                conn._pg.rollback()
        except Exception:
            conn = None
        else:
            # Callers set row_factory right after connecting (or not at all), so
            # reset it - otherwise one module's setting leaks into the next caller.
            conn.row_factory = None
            conn._shared = True
            return conn

    conn = _open_with_retry(dsn, schema)
    conn._shared = True
    _pool[schema] = conn
    return conn


def _open_with_retry(dsn, schema):
    """Open a pooled connection, retrying a few times on a transient failure.

    A suspended free-tier Neon instance or a briefly unavailable pooler refuses
    the first connection for a second or two, and because the app opens a
    connection per schema during import that single blip would abort startup.
    Retries are bounded and only cover the *connect*; once a connection exists,
    statement handling is governed by the read-only retry in Connection.execute.
    """
    attempts = _int_env('HB_DB_CONNECT_ATTEMPTS', 3)
    delay = _int_env('HB_DB_CONNECT_RETRY_DELAY', 1.5)

    last = None
    for attempt in range(1, attempts + 1):
        try:
            return Connection(dsn, schema)
        except Exception as exc:
            last = exc
            if attempt == attempts:
                break
            _time.sleep(delay * attempt)

    raise last


def _release(schema, conn):
    """Return a pooled connection, rolling back any dangling transaction."""
    if _pool.get(schema) is conn:
        try:
            if conn._pg.info.transaction_status != _get_pg_status_idle():
                conn._pg.rollback()
        except Exception:
            _pool[schema] = None
    try:
        conn._shared = False
    except Exception:
        pass


def _split_statements(script):
    """Split a multi-statement script on semicolons outside literals."""
    chunks = _split_literals(script)
    parts, current = [], []
    for is_lit, text in chunks:
        if is_lit:
            current.append(text)
        else:
            buf = []
            for ch in text:
                if ch == ';':
                    stmt = ''.join(current + buf).strip()
                    if stmt:
                        parts.append(stmt)
                    current, buf = [], []
                else:
                    buf.append(ch)
            current.append(''.join(buf))
    tail = ''.join(current).strip()
    if tail:
        parts.append(tail)
    return parts


