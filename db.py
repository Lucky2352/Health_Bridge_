def connect(db_file=None, *args, **kwargs):
    """Open a connection, mirroring ``sqlite3.connect()``.

    Returns a :class:`Connection` bound to the PostgreSQL schema that matches
    ``db_file``, or a genuine ``sqlite3`` connection when ``HB_DB_BACKEND=sqlite``.

    PostgreSQL connections are pooled per schema. The calling code keeps doing
    ``conn.close()`` exactly as it always did; that simply returns the
    connection to the pool instead of tearing down a socket.
    """
    url = _database_url()
    if _force_sqlite() or not url:
        return _sqlite3.connect(db_file or ':memory:')
    schema = _schema_for(db_file) if db_file else DEFAULT_SCHEMA
    return _acquire(url, schema)


def server_version():
    """Return the connected PostgreSQL server version string.

    Queried lazily on first call. Nothing in the app asks for it - the schema
    setup used to fetch it eagerly, which cost an extra round trip through the
    pooler on every fresh process to fill in a value no code read.
    """
    global _server_version
    if _server_version is None:
        url = _database_url()
        if _force_sqlite() or not url:
            return None
        try:
            with _get_psycopg().connect(url, **{**_connect_kwargs(), 'autocommit': True}) as pg:
                with pg.cursor() as cur:
                    cur.execute('SHOW server_version')
                    _server_version = cur.fetchone()[0]
        except Exception:
            return None
    return _server_version


def is_postgres():
    """True when connections are being served by PostgreSQL."""
    return bool(_database_url()) and not _force_sqlite()


def close_all():
    """Close every pooled connection. Call this on application shutdown."""
    for schema in list(_pool):
        conn = _pool[schema]
        _pool[schema] = None
        if conn is not None:
            try:
                conn._pg.close()
            except Exception:
                pass


