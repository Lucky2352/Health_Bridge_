def _split_literals(sql):
    """Yield (is_literal, chunk) so we can rewrite only real SQL, not strings.

    Protects single-quoted strings, double-quoted identifiers, ``--`` line
    comments and ``/* */`` block comments from the token rewrites below.
    """
    i, n = 0, len(sql)
    buf = []
    while i < n:
        ch = sql[i]
        if ch == "'":
            j = i + 1
            while j < n:
                if sql[j] == "'":
                    if j + 1 < n and sql[j + 1] == "'":
                        j += 2
                        continue
                    j += 1
                    break
                j += 1
            buf.append((True, sql[i:j]))
            i = j
        elif ch == '"':
            j = sql.find('"', i + 1)
            j = n if j == -1 else j + 1
            buf.append((True, sql[i:j]))
            i = j
        elif ch == '-' and sql.startswith('--', i):
            j = sql.find('\n', i)
            j = n if j == -1 else j
            buf.append((True, sql[i:j]))
            i = j
        elif ch == '/' and sql.startswith('/*', i):
            j = sql.find('*/', i + 2)
            j = n if j == -1 else j + 2
            buf.append((True, sql[i:j]))
            i = j
        else:
            buf.append((False, ch))
            i += 1
    return buf


def _join(chunks):
    return ''.join(text for _, text in chunks)


def _map_outside_literals(chunks, fn):
    return [(is_lit, fn(text) if not is_lit else text) for is_lit, text in chunks]


_STRFTIME_RE = re.compile(r"strftime\s*\(\s*'([^']*)'\s*", re.IGNORECASE)
_DATE_NOW_RE = re.compile(r"date\s*\(\s*'now'\s*(?:,\s*'([^']*)'\s*)?\)", re.IGNORECASE)
_INTERVAL_UNITS = {
    'day': 'days', 'days': 'days',
    'week': 'weeks', 'weeks': 'weeks',
    'month': 'months', 'months': 'months',
    'year': 'years', 'years': 'years',
    'hour': 'hours', 'hours': 'hours',
    'minute': 'minutes', 'minutes': 'minutes',
    'second': 'seconds', 'seconds': 'seconds',
}

_STRFTIME_MAP = [
    ('%Y', 'YYYY'), ('%m', 'MM'), ('%d', 'DD'),
    ('%H', 'HH24'), ('%M', 'MI'), ('%S', 'SS'),
    ('%y', 'YY'), ('%j', 'DDD'), ('%W', 'WW'),
]


def _to_pg_timestamp_format(fmt):
    for src, dst in _STRFTIME_MAP:
        fmt = fmt.replace(src, dst)
    return fmt


def _date_now_repl(m):
    modifier = m.group(1)
    if not modifier:
        return 'CURRENT_DATE'
    mm = re.match(r'\s*([+-]?\d+)\s+([a-z]+)\s*$', modifier.strip())
    if not mm:
        return 'CURRENT_DATE'
    amount, unit = mm.group(1), _INTERVAL_UNITS.get(mm.group(2).lower())
    if not unit:
        return 'CURRENT_DATE'
    return f"CURRENT_DATE - INTERVAL '{amount.lstrip('+-')} {unit}'"


def _rewrite_insert_or_replace(sql):
    """``INSERT OR REPLACE INTO t (a,b) VALUES (?,?)`` -> INSERT ... ON CONFLICT DO UPDATE."""
    m = re.match(
        r'(\s*INSERT\s+OR\s+REPLACE\s+INTO\s+([\w".]+)\s*\(([^)]*)\)\s*VALUES\s*\()',
        sql, re.IGNORECASE | re.DOTALL)
    if not m:
        return sql

    head, col_list = m.group(1), m.group(3)
    tail = sql[m.end():]                      # everything after "VALUES ("
    cols = [c.strip().strip('"') for c in col_list.split(',') if c.strip()]
    assignments = ', '.join(f'"{c}" = EXCLUDED."{c}"' for c in cols)
    rewritten = re.sub(r'INSERT\s+OR\s+REPLACE', 'INSERT', head, flags=re.IGNORECASE) + tail

    stripped = rewritten.rstrip()
    if stripped.endswith(';'):
        stripped = stripped[:-1].rstrip()
    return f'{stripped} ON CONFLICT DO UPDATE SET {assignments};'


def _rewrite_alter_add_column(sql):
    """``ALTER TABLE t ADD COLUMN c TEXT UNIQUE`` -> two statements (PG forbids UNIQUE here)."""
    m = re.match(
        r'\s*ALTER\s+TABLE\s+([\w".]+)\s+ADD\s+COLUMN\s+([\w"]+)\s+(.*?);?\s*$',
        sql, re.IGNORECASE | re.DOTALL)
    if not m:
        return sql

    table, column, rest = m.group(1), m.group(2).strip('"'), m.group(3).rstrip(' ;')
    unique = bool(re.search(r'\bUNIQUE\b', rest, re.IGNORECASE))
    rest_clean = re.sub(r'\bUNIQUE\b', '', rest, flags=re.IGNORECASE).strip()

    statement = f'ALTER TABLE {table} ADD COLUMN {column} {rest_clean};'
    if unique:
        bare = table.replace('"', '')
        idx = f'idx_{bare}_{column}'.lower().replace('.', '_')
        statement += (
            f' CREATE UNIQUE INDEX IF NOT EXISTS {idx} ON {table} ({column});'
        )
    return statement


def translate_sql(sql, boolean_columns=(), schema=None, tables=()):
    """Rewrite SQLite-flavoured SQL into PostgreSQL-flavoured SQL.

    ``boolean_columns`` is the set of column names that are real ``BOOLEAN``
    columns in the target schema. SQLite has no boolean type - it stores 0/1 and
    happily compares a flag column against the integer 1 - so those comparisons
    have to become ``= TRUE`` / ``= FALSE`` or PostgreSQL rejects them with
    ``operator does not exist: boolean = integer``.

    ``schema``/``tables`` enable schema-qualification of every table reference.
    That is deliberate: the Neon connection string uses the ``-pooler`` host,
    which is PgBouncer in *transaction* pooling mode. A session-level
    ``SET search_path`` is only reliable inside a single transaction, because
    PgBouncer may hand the next transaction to a different backend server.
    Qualifying names explicitly makes the SQL correct no matter which backend
    ends up serving it.
    """
    if not sql:
        return sql

    stripped = sql.strip()

    # PRAGMA has no PostgreSQL equivalent and is always advisory here.
    if re.match(r'\s*PRAGMA\b', stripped, re.IGNORECASE):
        return 'SELECT 1'

    if re.match(r'\s*INSERT\s+OR\s+REPLACE\b', stripped, re.IGNORECASE):
        # NOTE: no ? -> %s pass here, so translate the body too.
        return _rewrite_insert_or_replace(
            stripped.replace('?', '%s') if '?' in stripped else stripped)

    if re.match(r'\s*ALTER\s+TABLE\b', stripped, re.IGNORECASE):
        # NOTE: no early return here. The rewritten ALTER still needs its target
        # schema-qualified - returning early sent it through search_path instead,
        # so "ALTER TABLE fhir_bundles ADD COLUMN ..." silently altered whichever
        # schema the pooled connection happened to be pointing at, which put
        # fhir_interop's upload_date column onto an unrelated table.
        sql = _rewrite_alter_add_column(stripped)

    # These constructs quote their own arguments, so they must run against the raw
    # SQL - the literal-aware pass below deliberately skips anything inside quotes.
    sql = _DATE_NOW_RE.sub(_date_now_repl, sql)
    sql = _rewrite_strftime_calls(sql)

    # SQLite's double-quoted-string fallback: role = "patient" -> role = 'patient'
    # (in PostgreSQL a double-quoted token is an identifier, not a value)
    sql = re.sub(r'=\s*"([^"]*)"', r"= '\1'", sql)

    if boolean_columns:
        sql = _rewrite_boolean_literals(sql, boolean_columns)

    if schema and tables:
        sql = _qualify_tables(sql, schema, tables)

    # CREATE/DROP TABLE targets are qualified unconditionally (see
    # _qualify_ddl_tables), because a brand-new table is not in ``tables`` yet
    # and would otherwise be created in whatever search_path happens to point at.
    if schema:
        sql = _qualify_ddl_tables(sql, schema)

    chunks = _split_literals(sql)

    # ? -> %s
    chunks = _map_outside_literals(chunks, lambda t: t.replace('?', '%s'))

    sql = _join(chunks)

    # Type / default keyword fixes.
    sql = re.sub(
        r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b',
        'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
        sql, flags=re.IGNORECASE)
    sql = re.sub(r'\bDATETIME\b', 'TIMESTAMP', sql, flags=re.IGNORECASE)
    sql = re.sub(r'\bBOOLEAN\s+DEFAULT\s+1\b', 'BOOLEAN DEFAULT TRUE', sql, flags=re.IGNORECASE)
    sql = re.sub(r'\bBOOLEAN\s+DEFAULT\s+0\b', 'BOOLEAN DEFAULT FALSE', sql, flags=re.IGNORECASE)

    return sql


# Keywords after which a bare table name is expected.
# ``REFERENCES`` is included so foreign-key targets in CREATE TABLE resolve in
# the right schema too, not just via search_path.
#
# The identifier must also match double-quoted names ("patients"): several call
# sites - migrate_sqlite_to_neon.py among them - quote the table name, and an
# unquoted-only pattern silently skipped those, leaving them to be resolved via
# search_path. Under the -pooler host (PgBouncer in transaction pooling mode)
# search_path is not preserved between transactions, so those statements failed
# intermittently with 42P01 "relation does not exist".
#
# An optional trailing ".ident" is captured so already-qualified references
# ("s"."t" / public.t) can be recognised and left alone rather than being
# qualified a second time.
_IDENT = r'(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_]*)'
_TABLE_REF_RE = re.compile(
    r'\b(FROM|JOIN|INTO|UPDATE|REFERENCES)\s+(' + _IDENT + r'(?:\s*\.\s*' + _IDENT + r')?)',
    re.IGNORECASE,
)


def _unqualify(name):
    """Strip quotes and any schema prefix from a table reference."""
    return name.replace('"', '').split('.')[-1].lower()


def _qualify_tables(sql, schema, tables):
    """Prefix bare table references with their schema.

    Only rewrites names that are actually tables in ``tables``, so CTE names,
    subquery aliases and column names are left alone.
    """
    known = set(tables)
    if not known:
        return sql

    def repl(m):
        keyword, name = m.group(1), m.group(2)
        # Already schema-qualified - qualifying again yields an invalid
        # three-part name ("s"."t"."t").
        if '.' in name:
            return m.group(0)
        # A CTE name or subquery alias, not a real table.
        if _unqualify(name) not in known:
            return m.group(0)
        # Double-quote a bare name so mixed-case tables keep resolving.
        quoted = name if name.startswith('"') else f'"{name}"'
        return f'{keyword} "{schema}".{quoted}'

    return _TABLE_REF_RE.sub(repl, sql)


# CREATE TABLE / DROP TABLE / ALTER TABLE carry no FROM/INTO keyword, so they
# need their own pattern. Unlike a SELECT target, a DDL target is unambiguously a
# real table - never a CTE name or alias - so it is qualified *unconditionally*.
# Without this, a table created before it exists in ``tables`` would fall back to
# search_path, and could silently land in ``public`` instead of its own schema.
# A possibly schema-qualified identifier: one segment, or segments joined by
# dots where each may be bare or double-quoted. Matching the *whole* qualified
# name matters - a pattern that only captures a single quoted identifier turns
# 'ALTER TABLE "s"."t"' into '"wrong"."s"."t"', because the trailing ".t" is
# then left outside the match and the captured half looks unqualified.
_IDENT = r'(?:"(?:[^"]|"")*"|[A-Za-z_][A-Za-z0-9_$]*)'
_QUALIFIED_IDENT = _IDENT + r'(?:\.' + _IDENT + r')*'

_CREATE_TABLE_RE = re.compile(
    r'\b(?P<head>(?:CREATE|DROP|ALTER)\s+TABLE)'
    r'(?P<exists>\s+IF\s+(?:NOT\s+)?EXISTS)?'
    r'(?P<only>\s+ONLY)?'
    r'\s+(?P<name>' + _QUALIFIED_IDENT + r')',
    re.IGNORECASE,
)


def _qualify_ddl_tables(sql, schema):
    """Schema-qualify CREATE/DROP/ALTER TABLE targets.

    Without this they fall back to ``search_path``, which the ``-pooler`` host
    (PgBouncer, transaction pooling) does not preserve between transactions.
    """

    def quote(name):
        """Double-quote a bare identifier; leave an already-quoted one alone."""
        return name if name.startswith('"') else f'"{name}"'

    def table_repl(m):
        name = m.group('name')
        # Already carries a schema prefix.
        if '.' in name:
            return m.group(0)
        head = f'{m.group("head")}{m.group("exists") or ""}{m.group("only") or ""}'
        return f'{head} "{schema}".{quote(name)}'

    def index_repl(m):
        name = m.group('name')
        if '.' in name:
            return m.group(0)
        return f'{m.group("head")} ON "{schema}".{quote(name)}'

    sql = _CREATE_TABLE_RE.sub(table_repl, sql)
    sql = _CREATE_INDEX_RE.sub(index_repl, sql)
    return _add_column_guard(sql)


# ``ALTER TABLE t ADD COLUMN c ...`` with no IF NOT EXISTS.
_ADD_COLUMN_RE = re.compile(
    r'(?P<head>\bALTER\s+TABLE\s+(?:ONLY\s+)?[\w".]+(?:\s+ADD\s+COLUMN)\s+)(?!IF\b)',
    re.IGNORECASE,
)

# Patterns used to keep the cached catalog lookups in step with executed DDL.
# The schema qualifier is optional because the translator emits qualified names,
# e.g. CREATE TABLE IF NOT EXISTS "patients"."patients".
_CREATE_TABLE_NAME_RE = re.compile(
    r'^\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?'
    r'(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\.\s*'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))',
    re.IGNORECASE,
)
_CREATE_TABLE_NAME_UNQUALIFIED_RE = re.compile(
    r'^\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))',
    re.IGNORECASE,
)
_ADD_COLUMN_NAME_RE = re.compile(
    r'^\s*ALTER\s+TABLE\s+(?:ONLY\s+)?[\w".]+\s+ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))\s+(?P<type>[A-Za-z ]+)',
    re.IGNORECASE,
)

# Only statements carrying their own no-op guard may be skipped.
_IF_NOT_EXISTS_RE = re.compile(r'IF\s+NOT\s+EXISTS', re.IGNORECASE)

_CREATE_INDEX_NAME_RE = re.compile(
    r'^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:CONCURRENTLY\s+)?(?:IF\s+NOT\s+EXISTS\s+)?'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))',
    re.IGNORECASE,
)

_ALTER_TARGET_TABLE_RE = re.compile(
    r'^\s*ALTER\s+TABLE\s+(?:ONLY\s+)?'
    r'(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\.\s*'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))',
    re.IGNORECASE,
)
_ALTER_TARGET_TABLE_UNQUALIFIED_RE = re.compile(
    r'^\s*ALTER\s+TABLE\s+(?:ONLY\s+)?'
    r'(?:"(?P<name>[^"]+)"|(?P<bare>[A-Za-z_][A-Za-z0-9_]*))',
    re.IGNORECASE,
)


def _alter_target_table(sql):
    """The lower-cased table an ``ALTER TABLE`` targets, or '' if unclear."""
    match = _ALTER_TARGET_TABLE_RE.match(sql) or _ALTER_TARGET_TABLE_UNQUALIFIED_RE.match(sql)
    return ((match.group('name') or match.group('bare') or '').lower()) if match else ''


def _add_column_guard(sql):
    """Add ``IF NOT EXISTS`` to ``ALTER TABLE ... ADD COLUMN``.

    Every ``init_db()`` in this codebase adds its extra columns with a bare
    ``ADD COLUMN`` wrapped in ``try/except OperationalError``, relying on the
    duplicate-column error as the "does it already exist" test. On PostgreSQL
    that costs a wasted statement and an aborted transaction every single start,
    which in turn forces the savepoint dance in ``Connection._execute_once``.

    PostgreSQL has native support for the guard, so supply it here. This only
    affects translated (PostgreSQL) statements - the SQLite fallback path does
    not go through the translator at all.
    """
    return _ADD_COLUMN_RE.sub(lambda m: m.group('head') + 'IF NOT EXISTS ', sql)


# ``ALTER TABLE ... ADD COLUMN c UNIQUE`` is rewritten into a companion
# CREATE UNIQUE INDEX, whose ON <table> target would otherwise be unqualified and
# so resolve through search_path.
_CREATE_INDEX_RE = re.compile(
    r'\b(?P<head>CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:CONCURRENTLY\s+)?IF\s+NOT\s+EXISTS\s+'
    r'(?P<idx>"[^"]+"|[A-Za-z_][A-Za-z0-9_]*))\s+ON\s+'
    r'(?P<name>' + _QUALIFIED_IDENT + r')',
    re.IGNORECASE,
)


def _rewrite_boolean_literals(sql, boolean_columns):
    """Rewrite ``flag_col = 1`` / ``= 0`` into ``= TRUE`` / ``= FALSE``."""
    names = sorted((c for c in boolean_columns if c), key=len, reverse=True)
    if not names:
        return sql
    pattern = re.compile(
        r'\b(' + '|'.join(re.escape(n) for n in names) + r')\s*=\s*([01])\b',
        re.IGNORECASE,
    )
    return pattern.sub(lambda m: f'{m.group(1)} = {"TRUE" if m.group(2) == "1" else "FALSE"}', sql)


def _rewrite_strftime_calls(sql):
    out = []
    i = 0
    while True:
        m = _STRFTIME_RE.search(sql, i)
        if not m:
            out.append(sql[i:])
            break

        out.append(sql[i:m.start()])

        # The regex already consumed strftime('fmt' - find the matching ')' for it.
        depth = 1
        j = m.end()
        while j < len(sql) and depth:
            if sql[j] == '(':
                depth += 1
            elif sql[j] == ')':
                depth -= 1
            j += 1

        fmt = m.group(1).strip()
        # Remaining args, i.e. everything the regex did not eat.
        rest = sql[m.end():j - 1].lstrip()
        if rest.startswith(','):
            rest = rest[1:].strip()

        out.append(f"to_char({rest}, '{_to_pg_timestamp_format(fmt)}')")
        i = j
    return ''.join(out)


