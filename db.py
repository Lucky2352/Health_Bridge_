"""
db.py -- PostgreSQL (Neon) compatibility layer for HealthBridge.

The application was originally written against the stdlib ``sqlite3`` module and
spread raw SQL across nine modules. Rather than rewriting every query by hand, this
module exposes the *same* surface the rest of the code already uses::

    conn = db.connect('patients.db')
    conn.row_factory = db.Row
    cur = conn.execute('SELECT * FROM patients WHERE patient_id = ?', (pid,))
    row = cur.fetchone()
    conn.commit(); conn.close()

...but backed by psycopg3 / PostgreSQL.

What it translates for you
--------------------------
===================  =========================================================
SQLite               PostgreSQL equivalent
===================  =========================================================
``?``                ``%s`` parameter placeholders
``AUTOINCREMENT``    ``GENERATED BY DEFAULT AS IDENTITY``
``DATETIME``         ``TIMESTAMP``
``BOOLEAN DEFAULT 1``  ``BOOLEAN DEFAULT TRUE``
``INSERT OR REPLACE``  ``INSERT ... ON CONFLICT DO UPDATE SET col=EXCLUDED.col``
``ALTER ... ADD c TEXT UNIQUE``  column + ``CREATE UNIQUE INDEX IF NOT EXISTS``
``date('now','-30 days')``  ``CURRENT_DATE - INTERVAL '30 days'``
``strftime('%Y-%m', x)``      ``to_char(x, 'YYYY-MM')``
``PRAGMA ...``         ignored (no-op)
``="text"``            ``='text'``  (SQLite's double-quoted-string fallback)
``sqlite3.Row``        ``db.Row``   (dict subclass, also indexable by position)
``cursor.lastrowid``   ``RETURNING id``
===================  =========================================================

Schema mapping
--------------
The app historically used five separate SQLite files. Each one maps to its own
PostgreSQL *schema* inside the single Neon database, so existing unqualified table
names keep working via ``search_path`` and no table-name collisions occur::

    patients.db        -> schema patients
    enhanced_auth.db   -> schema enhanced_auth
    diagnosis.db       -> schema diagnosis
    fhir_data.db       -> schema fhir_data
    fhir_bundles.db    -> schema fhir_bundles

Falling back to SQLite
----------------------
If ``DATABASE_URL`` is not set (or Neon is unreachable) and ``HB_DB_BACKEND=sqlite``
is set, :func:`connect` transparently returns a real ``sqlite3`` connection instead,
so the app keeps working offline. That is how the one-time data migration reads the
legacy files.
"""

