#: Keys already passed to :func:`ensure_once` in this process.
_initialised_tables = set()
_init_lock = threading.Lock()


def singleton(func):
    """Decorate a zero-arg factory so its result is built once per process.

    Wraps the hand-rolled ``if x is None: x = X()`` caches that were repeated
    across the route modules, adding the two things those all lacked: a lock, so
    two threads hitting a blueprint for the first time cannot both construct the
    object and run its schema setup, and no marking-on-failure, so a constructor
    that raises does not leave a broken object cached for the life of the process.

    The attribute name on the wrapper is deliberately unhelpful so that a missed
    call site reads as an error here rather than silently working in dev and
    failing under the threaded server.
    """

    sentinel = object()
    result = sentinel
    lock = threading.Lock()

    @functools.wraps(func)
    def get():
        nonlocal result
        if result is not sentinel:
            return result
        with lock:
            if result is sentinel:
                result = func()
            return result

    return get


def ensure_once(key, setup):
    """Run ``setup`` the first time ``key`` is seen in this process.

    Every ``init_db()``/``init_database()`` in this codebase issues the same
    CREATE TABLE IF NOT EXISTS / ALTER TABLE ADD COLUMN statements, and they run
    from a constructor. Constructors here are called at import time *and* inside
    request handlers, so those idempotent statements were being re-sent over the
    wire on every start and on many individual requests - roughly a dozen round
    trips each, which on the Neon ``-pooler`` endpoint (PgBouncer in transaction
    pooling mode) cost seconds, not milliseconds. That was the entire startup
    time.

    The statements are already written to be idempotent, so running them once is
    behaviourally identical to running them every time - only the repetition goes
    away. ``key`` must identify the *table set*, not just the file: two classes
    share ``enhanced_auth.db`` and create different tables, so keying on the file
    alone would let whichever ran first suppress the other's DDL.

    Returns True when ``setup`` ran. A failure propagates and leaves ``key``
    unmarked, so the next caller retries rather than proceeding against a schema
    that was never created.
    """
    if key in _initialised_tables:
        return False
    with _init_lock:
        # Re-checked under the lock: the dev server is threaded, so two first
        # requests can arrive together.
        if key in _initialised_tables:
            return False
        setup()
        _initialised_tables.add(key)
    return True


def _schema_for(db_file):
    """Resolve a (possibly absolute) SQLite path to a PostgreSQL schema name."""
    name = os.path.basename(str(db_file))
    return SCHEMA_MAP.get(name, DEFAULT_SCHEMA)


# --------------------------------------------------------------------------- #
# Exceptions
# --------------------------------------------------------------------------- #
# These names ARE the stdlib ones, deliberately, rather than a parallel hierarchy
# that happens to share a spelling.
#
# The codebase catches ``db.OperationalError`` to mean "the object already exists"
# and ``db.IntegrityError`` to mean "duplicate key". On PostgreSQL those catches
# receive the errors :func:`_translate_error` re-raises, so they need the db names.
# On SQLite the driver raises its own exceptions, which those same catches do not
# recognise - so every idempotent ``ALTER TABLE ... ADD COLUMN`` guard escaped its
# handler and took the boot down with it.
#
# Subclassing cannot fix that: ``except db.X`` matches subclasses of ``db.X``, and
# sqlite3 has already built its exceptions by the time we get a say, so
# ``sqlite3.OperationalError`` will never be an instance of some subclass of ours.
# Aliasing is the only thing that makes one name denote one type, which is what
# lets a single except-clause catch a translated PostgreSQL error and a native
# SQLite one alike.
#
# sqlite3's own hierarchy already matches what is needed:
#   Error <- DatabaseError <- {OperationalError, IntegrityError, DataError}
# so aliasing preserves the parent/child relationships :func:`_translate_error` and
# its SQLSTATE map rely on.

Error = _sqlite3.Error
DatabaseError = _sqlite3.DatabaseError
OperationalError = _sqlite3.OperationalError
IntegrityError = _sqlite3.IntegrityError
DataError = _sqlite3.DataError


_SQLSTATE_MAP = {
    '42701': OperationalError,   # duplicate_column
    '42703': OperationalError,   # undefined_column
    '42P01': OperationalError,   # undefined_table
    '42P07': OperationalError,   # duplicate_table
    '42P06': OperationalError,   # duplicate_schema
    '42501': OperationalError,   # insufficient_privilege
    '22001': DataError,          # string_data_right_truncation
    '22P02': DataError,          # invalid_text_representation
    '22003': DataError,          # numeric_value_out_of_range
    '22007': DataError,          # invalid_datetime_format
    '22008': DataError,          # datetime_field_overflow
    '22012': DataError,          # division_by_zero
}


def _translate_error(exc):
    """Re-raise a psycopg error under a sqlite3-compatible name."""
    sqlstate = getattr(exc, 'sqlstate', None) or ''
    if sqlstate.startswith('23'):
        cls = IntegrityError
    else:
        cls = _SQLSTATE_MAP.get(sqlstate, DatabaseError)
    return cls(f'{sqlstate}: {exc}').with_traceback(exc.__traceback__)


